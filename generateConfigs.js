'use strict';

/**
 * TrustGuard IIoT — Network Config Generator v1.0
 * 
 * Reads network-config.json and generates:
 *   1. configtx.yaml
 *   2. docker-compose.yaml
 *   3. scripts/registerEnroll.sh
 *   4. safety-chaincode/lib/safetyContract.js
 *   5. scripts/network.sh (updated peer/orderer refs)
 *   6. .env files for backend and gateway
 * 
 * Usage:
 *   node generateConfigs.js [--config path/to/network-config.json] [--out ./output]
 */

const fs   = require('fs');
const path = require('path');

// ── Parse CLI args ────────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const configPath = args.includes('--config')
  ? args[args.indexOf('--config') + 1]
  : path.join(__dirname, 'network-config.json');
const outDir = args.includes('--out')
  ? args[args.indexOf('--out') + 1]
  : path.join(__dirname, 'generated');

const cfg = JSON.parse(fs.readFileSync(configPath, 'utf8'));
fs.mkdirSync(path.join(outDir, 'scripts'),               { recursive: true });
fs.mkdirSync(path.join(outDir, 'docker'),                { recursive: true });
fs.mkdirSync(path.join(outDir, 'safety-chaincode', 'lib'), { recursive: true });

const orgs = cfg.organizations;
const ord  = cfg.orderer;
const net  = cfg.network;
const cc   = cfg.chaincode;
const dash = cfg.dashboard;

console.log(`\nTrustGuard IIoT — Config Generator`);
console.log(`Network  : ${net.name}`);
console.log(`Channel  : ${net.channel}`);
console.log(`Orgs     : ${orgs.map(o => o.id).join(', ')}`);
console.log(`Output   : ${outDir}\n`);

// ═══════════════════════════════════════════════════════════════════════════════
// 1. configtx.yaml
// ═══════════════════════════════════════════════════════════════════════════════
function genConfigtx() {
  const orgSections = orgs.map(org => `
    - &${org.name}
        Name: ${org.id}
        ID:   ${org.id}
        MSPDir: organizations/peerOrganizations/${org.domain}/msp
        Policies:
            Readers:
                Type: Signature
                Rule: "OR('${org.id}.admin', '${org.id}.peer', '${org.id}.client')"
            Writers:
                Type: Signature
                Rule: "OR('${org.id}.admin', '${org.id}.client')"
            Admins:
                Type: Signature
                Rule: "OR('${org.id}.admin')"
            Endorsement:
                Type: Signature
                Rule: "OR('${org.id}.peer')"
        AnchorPeers:
            - Host: peer0.${org.domain}
              Port: ${org.peerPort}`).join('\n');

  // Endorsement policy for Application section
  const endorseRule = cc.endorsementPolicy === 'MAJORITY'
    ? `"MAJORITY Member"`
    : `"OR(${orgs.map(o => `'${o.id}.peer'`).join(', ')})"`;

  // Consenters block — one entry per orderer node
  const nodeCount = ord.nodeCount || 1;
  const consenters = Array.from({ length: nodeCount }, (_, i) => {
    const prefix = nodeCount === 1 ? 'orderer' : `orderer${i}`;
    return `
            - Host: ${prefix}.${ord.domain}
              Port: ${ord.port}
              ClientTLSCert: organizations/ordererOrganizations/${ord.domain}/orderers/${prefix}.${ord.domain}/tls/server.crt
              ServerTLSCert: organizations/ordererOrganizations/${ord.domain}/orderers/${prefix}.${ord.domain}/tls/server.crt`;
  }).join('\n');

  const ordererAddresses = Array.from({ length: nodeCount }, (_, i) => {
    const prefix = nodeCount === 1 ? 'orderer' : `orderer${i}`;
    return `    - ${prefix}.${ord.domain}:${ord.port}`;
  }).join('\n');

  const yaml = `---
# Generated by TrustGuard IIoT generateConfigs.js
# Network: ${net.name}  |  Channel: ${net.channel}

Organizations:
${orgSections}

    - &${ord.orgName}
        Name: ${ord.orgName}
        ID:   ${ord.orgName}
        MSPDir: organizations/ordererOrganizations/${ord.domain}/msp
        Policies:
            Readers:
                Type: Signature
                Rule: "OR('${ord.orgName}.member')"
            Writers:
                Type: Signature
                Rule: "OR('${ord.orgName}.member')"
            Admins:
                Type: Signature
                Rule: "OR('${ord.orgName}.admin')"

Capabilities:
    Channel: &ChannelCapabilities
        V2_0: true
    Orderer: &OrdererCapabilities
        V2_0: true
    Application: &ApplicationCapabilities
        V2_5: true

Application: &ApplicationDefaults
    Organizations:
    Policies:
        Readers:
            Type: ImplicitMeta
            Rule: "ANY Readers"
        Writers:
            Type: ImplicitMeta
            Rule: "ANY Writers"
        Admins:
            Type: ImplicitMeta
            Rule: "MAJORITY Admins"
        LifecycleEndorsement:
            Type: ImplicitMeta
            Rule: "MAJORITY Endorsement"
        Endorsement:
            Type: ImplicitMeta
            Rule: "MAJORITY Endorsement"
    Capabilities:
        <<: *ApplicationCapabilities

Orderer: &OrdererDefaults
    OrdererType: etcdraft
    Addresses:
${ordererAddresses}
    EtcdRaft:
        Consenters:
${consenters}
        Options:
            TickInterval:         500ms
            ElectionTick:         10
            HeartbeatTick:        1
            MaxInflightBlocks:    5
            SnapshotIntervalSize: 16 MB
    BatchTimeout: ${ord.batchTimeout}
    BatchSize:
        MaxMessageCount:   ${ord.maxMessageCount}
        AbsoluteMaxBytes:  ${ord.absoluteMaxBytes}
        PreferredMaxBytes: ${ord.preferredMaxBytes}
    Organizations:
    Policies:
        Readers:
            Type: ImplicitMeta
            Rule: "ANY Readers"
        Writers:
            Type: ImplicitMeta
            Rule: "ANY Writers"
        Admins:
            Type: ImplicitMeta
            Rule: "MAJORITY Admins"
        BlockValidation:
            Type: ImplicitMeta
            Rule: "ANY Writers"
    Capabilities:
        <<: *OrdererCapabilities

Channel: &ChannelDefaults
    Policies:
        Readers:
            Type: ImplicitMeta
            Rule: "ANY Readers"
        Writers:
            Type: ImplicitMeta
            Rule: "ANY Writers"
        Admins:
            Type: ImplicitMeta
            Rule: "MAJORITY Admins"
    Capabilities:
        <<: *ChannelCapabilities

Profiles:
    ${net.genesisProfile || 'IINoTSafetyGenesis'}:
        <<: *ChannelDefaults
        Orderer:
            <<: *OrdererDefaults
            Organizations:
                - *${ord.anchorName || ord.orgName}
            Capabilities:
                <<: *OrdererCapabilities
        Application:
            <<: *ApplicationDefaults
            Organizations:
${orgs.map(o => `                - *${o.name}`).join('\n')}
            Capabilities:
                <<: *ApplicationCapabilities
`;
  fs.writeFileSync(path.join(outDir, 'configtx.yaml'), yaml);
  console.log('✅ configtx.yaml');
}

