// 3. scripts/registerEnroll.sh
// ═══════════════════════════════════════════════════════════════════════════════
function genRegisterEnroll() {
  const orgFunctions = orgs.map(org => {
    const roleRegistrations = org.roles.map(role => `
    fabric-ca-client register --caname ${org.caName || 'ca-' + org.domain.split('.')[0]} \\
        --id.name ${role.name} --id.secret ${role.secret} \\
        --id.type client --id.attrs "${role.attrs}" \\
        --tls.certfiles "$FABRIC_CA_CLIENT_HOME/fabric-ca-client-config.yaml" \\
        --mspdir "$CA_ADMIN_MSP" 2>&1`).join('\n');

    const roleEnrollments = org.roles.map(role => `
    mkdir -p "\${WALLET_DIR}/${role.name}"
    fabric-ca-client enroll \\
        -u "https://${role.name}:${role.secret}@localhost:${org.caPort}" \\
        --caname ${org.caName || 'ca-' + org.domain.split('.')[0]} \\
        -M "\${WALLET_DIR}/${role.name}/msp" \\
        --enrollment.attrs "${role.attrs.split(':')[0]},hf.Affiliation" \\
        --tls.certfiles "\${ORGDIR}/fabric-ca/${org.caFolderName || org.domain.split('.')[0]}/ca-cert.pem" 2>&1
    # Copy cert and key for SDK wallet
    cp "\${WALLET_DIR}/${role.name}/msp/signcerts/"*.pem "\${WALLET_DIR}/${role.name}/cert.pem" 2>/dev/null || true
    cp "\${WALLET_DIR}/${role.name}/msp/keystore/"*_sk "\${WALLET_DIR}/${role.name}/key.pem" 2>/dev/null || true`).join('\n');

    return `
function create${org.name}() {
    echo "[INFO] Setting up ${org.id}..."
    ORGDIR="$SCRIPT_DIR/../organizations"
    CA_ADMIN_MSP="\${ORGDIR}/peerOrganizations/${org.domain}/users/Admin@${org.domain}/msp"

    # Enroll CA admin
    fabric-ca-client enroll \\
        -u "https://${org.caAdminUser}:${org.caAdminPassword}@localhost:${org.caPort}" \\
        --caname ${org.caName || 'ca-' + org.domain.split('.')[0]} \\
        -M "\${ORGDIR}/peerOrganizations/${org.domain}/users/Admin@${org.domain}/msp" \\
        --tls.certfiles "\${ORGDIR}/fabric-ca/${org.caFolderName || org.domain.split('.')[0]}/ca-cert.pem" 2>&1

    # Register application identities
${roleRegistrations}

    # Enroll peer0 MSP
    fabric-ca-client enroll \\
        -u "https://peer0:peer0pw@localhost:${org.caPort}" \\
        --caname ${org.caName || 'ca-' + org.domain.split('.')[0]} \\
        -M "\${ORGDIR}/peerOrganizations/${org.domain}/peers/peer0.${org.domain}/msp" \\
        --csr.hosts "peer0.${org.domain},localhost" \\
        --tls.certfiles "\${ORGDIR}/fabric-ca/${org.caFolderName || org.domain.split('.')[0]}/ca-cert.pem" 2>&1

    # Enroll peer0 TLS
    fabric-ca-client enroll \\
        -u "https://peer0:peer0pw@localhost:${org.caPort}" \\
        --caname ${org.caName || 'ca-' + org.domain.split('.')[0]} \\
        --enrollment.profile tls \\
        -M "\${ORGDIR}/peerOrganizations/${org.domain}/peers/peer0.${org.domain}/tls" \\
        --csr.hosts "peer0.${org.domain},localhost" \\
        --tls.certfiles "\${ORGDIR}/fabric-ca/${org.caFolderName || org.domain.split('.')[0]}/ca-cert.pem" 2>&1

    # Enroll application identities into wallet
${roleEnrollments}

    echo "[SUCCESS] ${org.id} identities ready."
}`;
  }).join('\n');

  const orgCalls = orgs.map(o => `create${o.name}`).join('\n');

  const sh = `#!/bin/bash
# Generated by TrustGuard IIoT generateConfigs.js
# Network: ${net.name}

set -e
SCRIPT_DIR="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
WALLET_DIR="\${SCRIPT_DIR}/../../safety-simulation/wallet"
export PATH="\${HOME}/fabric/fabric-samples/bin:\${PATH}"
export FABRIC_CA_CLIENT_HOME="\${SCRIPT_DIR}/../"

mkdir -p "\${WALLET_DIR}"

${orgFunctions}

function createOrderer() {
    echo "[INFO] Setting up ${ord.orgName}..."
    ORGDIR="\$SCRIPT_DIR/../organizations"

    fabric-ca-client enroll \\
        -u "https://admin:adminpw@localhost:${ord.caPort}" \\
        --caname ${ord.caName || 'ca-iinot-orderer'} \\
        -M "\${ORGDIR}/ordererOrganizations/${ord.domain}/users/Admin@${ord.domain}/msp" \\
        --tls.certfiles "\${ORGDIR}/fabric-ca/${ord.caFolderName || 'iinot-orderer'}/ca-cert.pem" 2>&1

    ${Array.from({ length: ord.nodeCount || 1 }, (_, i) => {
      const prefix = (ord.nodeCount || 1) === 1 ? 'orderer' : `orderer${i}`;
      return `
    # ${prefix}
    fabric-ca-client enroll \\
        -u "https://${prefix}:ordererpw@localhost:${ord.caPort}" \\
        --caname ${ord.caName || 'ca-iinot-orderer'} \\
        -M "\${ORGDIR}/ordererOrganizations/${ord.domain}/orderers/${prefix}.${ord.domain}/msp" \\
        --csr.hosts "${prefix}.${ord.domain},localhost" \\
        --tls.certfiles "\${ORGDIR}/fabric-ca/${ord.caFolderName || 'iinot-orderer'}/ca-cert.pem" 2>&1

    fabric-ca-client enroll \\
        -u "https://${prefix}:ordererpw@localhost:${ord.caPort}" \\
        --caname ${ord.caName || 'ca-iinot-orderer'} \\
        --enrollment.profile tls \\
        -M "\${ORGDIR}/ordererOrganizations/${ord.domain}/orderers/${prefix}.${ord.domain}/tls" \\
        --csr.hosts "${prefix}.${ord.domain},localhost" \\
        --tls.certfiles "\${ORGDIR}/fabric-ca/${ord.caFolderName || 'iinot-orderer'}/ca-cert.pem" 2>&1`;
    }).join('\n')}

    echo "[SUCCESS] ${ord.orgName} identities ready."
}

# Run all
createOrderer
${orgCalls}

echo ""
echo "All identities enrolled successfully."
echo "Wallet: \${WALLET_DIR}"
`;
  fs.writeFileSync(path.join(outDir, 'scripts', 'registerEnroll.sh'), sh);
  fs.chmodSync(path.join(outDir, 'scripts', 'registerEnroll.sh'), '755');
  console.log('✅ scripts/registerEnroll.sh');
}

